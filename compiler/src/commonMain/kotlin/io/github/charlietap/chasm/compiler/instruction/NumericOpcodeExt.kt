internal val NumericOpcode.isBitcast: Boolean
    get() = when (this) {
        NumericOpcode.I32ReinterpretF32,
        NumericOpcode.I64ReinterpretF64,
        NumericOpcode.F32ReinterpretI32,
        NumericOpcode.F64ReinterpretI64,
        -> true
        else -> false
    }

