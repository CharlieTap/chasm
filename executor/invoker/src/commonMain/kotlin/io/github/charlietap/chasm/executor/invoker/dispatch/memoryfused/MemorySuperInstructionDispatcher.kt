package io.github.charlietap.chasm.executor.invoker.dispatch.memoryfused

import io.github.charlietap.chasm.runtime.dispatch.DispatchableInstruction
import io.github.charlietap.chasm.runtime.instruction.MemorySuperInstruction

fun MemorySuperInstructionDispatcher(
    instruction: MemorySuperInstruction,
): DispatchableInstruction = when (instruction) {
    is MemorySuperInstruction.I32LoadI -> I32LoadDispatcher(instruction)
    is MemorySuperInstruction.I32LoadS -> I32LoadDispatcher(instruction)
    is MemorySuperInstruction.I64LoadI -> I64LoadDispatcher(instruction)
    is MemorySuperInstruction.I64LoadS -> I64LoadDispatcher(instruction)
    is MemorySuperInstruction.F32LoadI -> F32LoadDispatcher(instruction)
    is MemorySuperInstruction.F32LoadS -> F32LoadDispatcher(instruction)
    is MemorySuperInstruction.F64LoadI -> F64LoadDispatcher(instruction)
    is MemorySuperInstruction.F64LoadS -> F64LoadDispatcher(instruction)
    is MemorySuperInstruction.I32Load8SI -> I32Load8SDispatcher(instruction)
    is MemorySuperInstruction.I32Load8SS -> I32Load8SDispatcher(instruction)
    is MemorySuperInstruction.I32Load8UI -> I32Load8UDispatcher(instruction)
    is MemorySuperInstruction.I32Load8US -> I32Load8UDispatcher(instruction)
    is MemorySuperInstruction.I32Load16SI -> I32Load16SDispatcher(instruction)
    is MemorySuperInstruction.I32Load16SS -> I32Load16SDispatcher(instruction)
    is MemorySuperInstruction.I32Load16UI -> I32Load16UDispatcher(instruction)
    is MemorySuperInstruction.I32Load16US -> I32Load16UDispatcher(instruction)
    is MemorySuperInstruction.I64Load8SI -> I64Load8SDispatcher(instruction)
    is MemorySuperInstruction.I64Load8SS -> I64Load8SDispatcher(instruction)
    is MemorySuperInstruction.I64Load8UI -> I64Load8UDispatcher(instruction)
    is MemorySuperInstruction.I64Load8US -> I64Load8UDispatcher(instruction)
    is MemorySuperInstruction.I64Load16SI -> I64Load16SDispatcher(instruction)
    is MemorySuperInstruction.I64Load16SS -> I64Load16SDispatcher(instruction)
    is MemorySuperInstruction.I64Load16UI -> I64Load16UDispatcher(instruction)
    is MemorySuperInstruction.I64Load16US -> I64Load16UDispatcher(instruction)
    is MemorySuperInstruction.I64Load32SI -> I64Load32SDispatcher(instruction)
    is MemorySuperInstruction.I64Load32SS -> I64Load32SDispatcher(instruction)
    is MemorySuperInstruction.I64Load32UI -> I64Load32UDispatcher(instruction)
    is MemorySuperInstruction.I64Load32US -> I64Load32UDispatcher(instruction)
    is MemorySuperInstruction.MemorySizeS -> MemorySizeDispatcher(instruction)
    is MemorySuperInstruction.MemoryGrowI -> MemoryGrowDispatcher(instruction)
    is MemorySuperInstruction.MemoryGrowS -> MemoryGrowDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitIii -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitIis -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitIsi -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitIss -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitSii -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitSis -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitSsi -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryInitSss -> MemoryInitDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopyIii -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopyIis -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopyIsi -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopyIss -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopySii -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopySis -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopySsi -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryCopySss -> MemoryCopyDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillIii -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillIis -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillIsi -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillIss -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillSii -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillSis -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillSsi -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.MemoryFillSss -> MemoryFillDispatcher(instruction)
    is MemorySuperInstruction.I32StoreIi -> I32StoreDispatcher(instruction)
    is MemorySuperInstruction.I32StoreIs -> I32StoreDispatcher(instruction)
    is MemorySuperInstruction.I32StoreSi -> I32StoreDispatcher(instruction)
    is MemorySuperInstruction.I32StoreSs -> I32StoreDispatcher(instruction)
    is MemorySuperInstruction.I64StoreIi -> I64StoreDispatcher(instruction)
    is MemorySuperInstruction.I64StoreIs -> I64StoreDispatcher(instruction)
    is MemorySuperInstruction.I64StoreSi -> I64StoreDispatcher(instruction)
    is MemorySuperInstruction.I64StoreSs -> I64StoreDispatcher(instruction)
    is MemorySuperInstruction.F32StoreIi -> F32StoreDispatcher(instruction)
    is MemorySuperInstruction.F32StoreIs -> F32StoreDispatcher(instruction)
    is MemorySuperInstruction.F32StoreSi -> F32StoreDispatcher(instruction)
    is MemorySuperInstruction.F32StoreSs -> F32StoreDispatcher(instruction)
    is MemorySuperInstruction.F64StoreIi -> F64StoreDispatcher(instruction)
    is MemorySuperInstruction.F64StoreIs -> F64StoreDispatcher(instruction)
    is MemorySuperInstruction.F64StoreSi -> F64StoreDispatcher(instruction)
    is MemorySuperInstruction.F64StoreSs -> F64StoreDispatcher(instruction)
    is MemorySuperInstruction.I32Store8Ii -> I32Store8Dispatcher(instruction)
    is MemorySuperInstruction.I32Store8Is -> I32Store8Dispatcher(instruction)
    is MemorySuperInstruction.I32Store8Si -> I32Store8Dispatcher(instruction)
    is MemorySuperInstruction.I32Store8Ss -> I32Store8Dispatcher(instruction)
    is MemorySuperInstruction.I32Store16Ii -> I32Store16Dispatcher(instruction)
    is MemorySuperInstruction.I32Store16Is -> I32Store16Dispatcher(instruction)
    is MemorySuperInstruction.I32Store16Si -> I32Store16Dispatcher(instruction)
    is MemorySuperInstruction.I32Store16Ss -> I32Store16Dispatcher(instruction)
    is MemorySuperInstruction.I64Store8Ii -> I64Store8Dispatcher(instruction)
    is MemorySuperInstruction.I64Store8Is -> I64Store8Dispatcher(instruction)
    is MemorySuperInstruction.I64Store8Si -> I64Store8Dispatcher(instruction)
    is MemorySuperInstruction.I64Store8Ss -> I64Store8Dispatcher(instruction)
    is MemorySuperInstruction.I64Store16Ii -> I64Store16Dispatcher(instruction)
    is MemorySuperInstruction.I64Store16Is -> I64Store16Dispatcher(instruction)
    is MemorySuperInstruction.I64Store16Si -> I64Store16Dispatcher(instruction)
    is MemorySuperInstruction.I64Store16Ss -> I64Store16Dispatcher(instruction)
    is MemorySuperInstruction.I64Store32Ii -> I64Store32Dispatcher(instruction)
    is MemorySuperInstruction.I64Store32Is -> I64Store32Dispatcher(instruction)
    is MemorySuperInstruction.I64Store32Si -> I64Store32Dispatcher(instruction)
    is MemorySuperInstruction.I64Store32Ss -> I64Store32Dispatcher(instruction)
}
