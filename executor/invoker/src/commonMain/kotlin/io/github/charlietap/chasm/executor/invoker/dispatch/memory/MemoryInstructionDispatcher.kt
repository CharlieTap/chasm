package io.github.charlietap.chasm.executor.invoker.dispatch.memory

import io.github.charlietap.chasm.runtime.dispatch.DispatchableInstruction
import io.github.charlietap.chasm.runtime.instruction.MemoryInstruction

fun MemoryInstructionDispatcher(
    instruction: MemoryInstruction,
): DispatchableInstruction = when (instruction) {
    is MemoryInstruction.I32LoadI -> I32LoadDispatcher(instruction)
    is MemoryInstruction.I32LoadS -> I32LoadDispatcher(instruction)
    is MemoryInstruction.I64LoadI -> I64LoadDispatcher(instruction)
    is MemoryInstruction.I64LoadS -> I64LoadDispatcher(instruction)
    is MemoryInstruction.F32LoadI -> F32LoadDispatcher(instruction)
    is MemoryInstruction.F32LoadS -> F32LoadDispatcher(instruction)
    is MemoryInstruction.F64LoadI -> F64LoadDispatcher(instruction)
    is MemoryInstruction.F64LoadS -> F64LoadDispatcher(instruction)
    is MemoryInstruction.I32Load8SI -> I32Load8SDispatcher(instruction)
    is MemoryInstruction.I32Load8SS -> I32Load8SDispatcher(instruction)
    is MemoryInstruction.I32Load8UI -> I32Load8UDispatcher(instruction)
    is MemoryInstruction.I32Load8US -> I32Load8UDispatcher(instruction)
    is MemoryInstruction.I32Load16SI -> I32Load16SDispatcher(instruction)
    is MemoryInstruction.I32Load16SS -> I32Load16SDispatcher(instruction)
    is MemoryInstruction.I32Load16UI -> I32Load16UDispatcher(instruction)
    is MemoryInstruction.I32Load16US -> I32Load16UDispatcher(instruction)
    is MemoryInstruction.I64Load8SI -> I64Load8SDispatcher(instruction)
    is MemoryInstruction.I64Load8SS -> I64Load8SDispatcher(instruction)
    is MemoryInstruction.I64Load8UI -> I64Load8UDispatcher(instruction)
    is MemoryInstruction.I64Load8US -> I64Load8UDispatcher(instruction)
    is MemoryInstruction.I64Load16SI -> I64Load16SDispatcher(instruction)
    is MemoryInstruction.I64Load16SS -> I64Load16SDispatcher(instruction)
    is MemoryInstruction.I64Load16UI -> I64Load16UDispatcher(instruction)
    is MemoryInstruction.I64Load16US -> I64Load16UDispatcher(instruction)
    is MemoryInstruction.I64Load32SI -> I64Load32SDispatcher(instruction)
    is MemoryInstruction.I64Load32SS -> I64Load32SDispatcher(instruction)
    is MemoryInstruction.I64Load32UI -> I64Load32UDispatcher(instruction)
    is MemoryInstruction.I64Load32US -> I64Load32UDispatcher(instruction)
    is MemoryInstruction.MemorySizeS -> MemorySizeDispatcher(instruction)
    is MemoryInstruction.MemoryGrowI -> MemoryGrowDispatcher(instruction)
    is MemoryInstruction.MemoryGrowS -> MemoryGrowDispatcher(instruction)
    is MemoryInstruction.MemoryInitIii -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryInitIis -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryInitIsi -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryInitIss -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryInitSii -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryInitSis -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryInitSsi -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryInitSss -> MemoryInitDispatcher(instruction)
    is MemoryInstruction.MemoryCopyIii -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryCopyIis -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryCopyIsi -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryCopyIss -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryCopySii -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryCopySis -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryCopySsi -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryCopySss -> MemoryCopyDispatcher(instruction)
    is MemoryInstruction.MemoryFillIii -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.MemoryFillIis -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.MemoryFillIsi -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.MemoryFillIss -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.MemoryFillSii -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.MemoryFillSis -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.MemoryFillSsi -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.MemoryFillSss -> MemoryFillDispatcher(instruction)
    is MemoryInstruction.I32StoreIi -> I32StoreDispatcher(instruction)
    is MemoryInstruction.I32StoreIs -> I32StoreDispatcher(instruction)
    is MemoryInstruction.I32StoreSi -> I32StoreDispatcher(instruction)
    is MemoryInstruction.I32StoreSs -> I32StoreDispatcher(instruction)
    is MemoryInstruction.I64StoreIi -> I64StoreDispatcher(instruction)
    is MemoryInstruction.I64StoreIs -> I64StoreDispatcher(instruction)
    is MemoryInstruction.I64StoreSi -> I64StoreDispatcher(instruction)
    is MemoryInstruction.I64StoreSs -> I64StoreDispatcher(instruction)
    is MemoryInstruction.F32StoreIi -> F32StoreDispatcher(instruction)
    is MemoryInstruction.F32StoreIs -> F32StoreDispatcher(instruction)
    is MemoryInstruction.F32StoreSi -> F32StoreDispatcher(instruction)
    is MemoryInstruction.F32StoreSs -> F32StoreDispatcher(instruction)
    is MemoryInstruction.F64StoreIi -> F64StoreDispatcher(instruction)
    is MemoryInstruction.F64StoreIs -> F64StoreDispatcher(instruction)
    is MemoryInstruction.F64StoreSi -> F64StoreDispatcher(instruction)
    is MemoryInstruction.F64StoreSs -> F64StoreDispatcher(instruction)
    is MemoryInstruction.I32Store8Ii -> I32Store8Dispatcher(instruction)
    is MemoryInstruction.I32Store8Is -> I32Store8Dispatcher(instruction)
    is MemoryInstruction.I32Store8Si -> I32Store8Dispatcher(instruction)
    is MemoryInstruction.I32Store8Ss -> I32Store8Dispatcher(instruction)
    is MemoryInstruction.I32Store16Ii -> I32Store16Dispatcher(instruction)
    is MemoryInstruction.I32Store16Is -> I32Store16Dispatcher(instruction)
    is MemoryInstruction.I32Store16Si -> I32Store16Dispatcher(instruction)
    is MemoryInstruction.I32Store16Ss -> I32Store16Dispatcher(instruction)
    is MemoryInstruction.I64Store8Ii -> I64Store8Dispatcher(instruction)
    is MemoryInstruction.I64Store8Is -> I64Store8Dispatcher(instruction)
    is MemoryInstruction.I64Store8Si -> I64Store8Dispatcher(instruction)
    is MemoryInstruction.I64Store8Ss -> I64Store8Dispatcher(instruction)
    is MemoryInstruction.I64Store16Ii -> I64Store16Dispatcher(instruction)
    is MemoryInstruction.I64Store16Is -> I64Store16Dispatcher(instruction)
    is MemoryInstruction.I64Store16Si -> I64Store16Dispatcher(instruction)
    is MemoryInstruction.I64Store16Ss -> I64Store16Dispatcher(instruction)
    is MemoryInstruction.I64Store32Ii -> I64Store32Dispatcher(instruction)
    is MemoryInstruction.I64Store32Is -> I64Store32Dispatcher(instruction)
    is MemoryInstruction.I64Store32Si -> I64Store32Dispatcher(instruction)
    is MemoryInstruction.I64Store32Ss -> I64Store32Dispatcher(instruction)
    is MemoryInstruction.DataDrop -> DataDropDispatcher(instruction)
}
